export const DICTIONARIES = { en, rw, fr };

const FALLBACK = 'en';

// Resolves a key for a language, interpolating {vars}. Unknown keys fall back to
// English and then to the key itself.
export function translate(lang, key, vars) {
  const dict = DICTIONARIES[lang] || DICTIONARIES[FALLBACK];
  const template = dict[key] ?? DICTIONARIES[FALLBACK][key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? `{${name}}`));
}

export default translate;
